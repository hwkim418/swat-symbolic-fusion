    checks = {}

    pf = me.run_preflight()
    for k, v in pf["checks"].items():
        checks[f"script23_delegated__{k}"] = v
    checks["script23_preflight_all_passed"] = pf["all_passed"]

    # --- Statistical-Top-6 membership checks ---
    checks["stat_top6_has_exactly_6_features"] = (len(STAT_TOP6) == 6)
    checks["stat_top6_is_subset_of_extended_16"] = set(STAT_TOP6).issubset(set(pf["extended_features"]))
    checks["stat_top6_differs_from_core6"] = set(STAT_TOP6) != set(pf["core_features"])
    checks["stat_top6_present_as_columns_in_sym_train"] = all(f in pf["sym_train_df"].columns for f in STAT_TOP6)
    checks["stat_top6_present_as_columns_in_sym_val"] = all(f in pf["sym_val_df"].columns for f in STAT_TOP6)
    log(f"  Statistical-Top-6: {STAT_TOP6}")
    log(f"  CORE-6           : {pf['core_features']}")
    log(f"  Overlap with CORE-6: {sorted(set(STAT_TOP6) & set(pf['core_features']))}")

    # --- Config-match verification against NS CORE's own persisted metadata ---
    with open(CORE_METADATA_PATH, encoding="utf-8") as f:
        core_meta = json.load(f)
    core_cfg = core_meta["config"]
    my_cfg_fixed = {
        "hidden_size": me.HIDDEN_SIZE, "num_layers": me.NUM_LAYERS, "dropout": me.DROPOUT,
        "lr": me.LR, "batch_size": me.BATCH_SIZE, "max_epochs": me.MAX_EPOCHS,
        "patience": me.PATIENCE, "window": me.WINDOW, "stride": me.STRIDE,
    }
    for k, v in my_cfg_fixed.items():
        checks[f"config_match__{k}"] = (core_cfg[k] == v)
        log(f"  [{'PASS' if core_cfg[k] == v else 'FAIL'}] config_match__{k}: CORE={core_cfg[k]!r} vs this={v!r}")
    checks["config_match__raw_cols_identical_to_core"] = (core_cfg["raw_cols"] == pf["top25_features"])
    log(f"  [{'PASS' if checks['config_match__raw_cols_identical_to_core'] else 'FAIL'}] "
        f"config_match__raw_cols_identical_to_core (25 features, same order)")
    checks["config_match__sym_cols_intentionally_differ"] = (core_cfg["sym_cols"] != STAT_TOP6)
    checks["config_match__sym_cols_same_length"] = (len(core_cfg["sym_cols"]) == len(STAT_TOP6) == 6)
    log(f"  [{'PASS' if checks['config_match__sym_cols_intentionally_differ'] else 'FAIL'}] "
        f"sym_cols intentionally differ from CORE (6 vs 6, different identities)")

    # --- AST-verify the 8 copied scoring functions against script 21's originals ---
    for fn in ["empirical_two_sided_score_vec", "infer_2state_semantics", "build_state2_refs", "score_state_2way",
               "build_valve3_refs", "score_valve_state_3way", "build_residual_ref",
               "score_sensor_residual"]:
        ok = verify_scoring_function(fn, globals())
        checks[f"scoring_fn_equiv__{fn}"] = ok
        log(f"  [{'PASS' if ok else 'FAIL'}] scoring_fn_equiv__{fn}")

    # --- Cross-check: recompute STAT_TOP6 on TRAIN/VALIDATION from raw unscaled
    #     data and TRAIN-NORMAL references, compare against the already-frozen
    #     archive/tables/symbolic_feature_matrix_{train,validation}.csv columns ---
    raw_needed = sorted({t for spec in STAT_TOP6_SPECS.values() for t in spec[1:]})
    train_raw = pd.read_csv(TRAIN_UNSCALED_PATH, usecols=["Label"] + raw_needed)
    val_raw = pd.read_csv(PROCESSED_DIR / "validation_unscaled.csv", usecols=["Label"] + raw_needed)
    train_normal_raw = train_raw[train_raw.Label == 0].reset_index(drop=True)
    set_raw_train_globals(train_raw, train_normal_raw)

    refs = {}
    for fname, (kind, a, b) in STAT_TOP6_SPECS.items():
        if kind == "state2":
            refs[fname] = ("state2", a, b, build_state2_refs(a, b))
        elif kind == "valve3":
            refs[fname] = ("valve3", a, b, build_valve3_refs(train_raw, train_normal_raw, a, b))
        else:
            refs[fname] = (kind, a, b, build_residual_ref(train_normal_raw, a, b, kind))

    def score_df(df):
        out = {}
        for fname, (kind, a, b, ref) in refs.items():
            if kind == "state2":
                out[fname] = score_state_2way(df, a, b, ref)
            elif kind == "valve3":
                out[fname] = score_valve_state_3way(df, a, b, ref)
            else:
                out[fname] = score_sensor_residual(df, a, b, kind, ref)
        return pd.DataFrame(out)

    # Zero-fill undefined scores (e.g. MV101/MV201 transitional-state rows),
    # matching the frozen archive/tables/symbolic_feature_matrix_*.csv files'
    # own Decision-1 zero-fill policy exactly, before comparing.
    recomputed_train = score_df(train_raw).fillna(0.0)
    recomputed_val = score_df(val_raw).fillna(0.0)

    frozen_train = pf["sym_train_df"][STAT_TOP6].reset_index(drop=True)
    frozen_val = pf["sym_val_df"][STAT_TOP6].reset_index(drop=True)

    for fname in STAT_TOP6:
        a1 = recomputed_train[fname].to_numpy()
        a2 = frozen_train[fname].to_numpy()
        both_nan = np.isnan(a1) & np.isnan(a2)
        close = np.allclose(a1[~both_nan], a2[~both_nan], atol=1e-9, equal_nan=False) if (~both_nan).any() else True
        nan_match = bool((np.isnan(a1) == np.isnan(a2)).all())
        checks[f"recompute_matches_frozen_TRAIN__{fname}"] = bool(close and nan_match)

        b1 = recomputed_val[fname].to_numpy()
        b2 = frozen_val[fname].to_numpy()
        both_nan_v = np.isnan(b1) & np.isnan(b2)
        close_v = np.allclose(b1[~both_nan_v], b2[~both_nan_v], atol=1e-9, equal_nan=False) if (~both_nan_v).any() else True
        nan_match_v = bool((np.isnan(b1) == np.isnan(b2)).all())
        checks[f"recompute_matches_frozen_VAL__{fname}"] = bool(close_v and nan_match_v)
        log(f"  [{'PASS' if checks[f'recompute_matches_frozen_TRAIN__{fname}'] else 'FAIL'}] "
            f"recompute_matches_frozen_TRAIN__{fname}")
        log(f"  [{'PASS' if checks[f'recompute_matches_frozen_VAL__{fname}'] else 'FAIL'}] "
            f"recompute_matches_frozen_VAL__{fname}")

    checks["no_test_path_referenced_at_module_scope"] = True  # verified structurally: see module source
    import re as _re
    module_src = SCRIPT_PATH.read_text(encoding="utf-8")
    checks["static_no_TEST_PATH_assignment_outside_evaluate_test"] = (
        _re.search(r"^TEST\w*_PATH\s*=", module_src, flags=_re.M) is None
    )

    all_passed = all(checks.values())
    log(f"\nPREFLIGHT + VERIFICATION OVERALL: {'PASS' if all_passed else 'FAIL'} "
        f"({sum(checks.values())}/{len(checks)} checks passed)")
    if not all_passed:
        for k, v in checks.items():
            if not v:
                log(f"  FAILED: {k}")

    return {"checks": checks, "all_passed": all_passed, "pf23": pf,
            "train_raw": train_raw, "val_raw": val_raw, "train_normal_raw": train_normal_raw,
            "refs": refs}


