def _normalize_func_src(func_name, src_text):
    """AST-normalize a function body (strip docstring) for source-equivalence
    comparison, mirroring code/26_final_test_evaluation.py's verify_function_equivalence."""
    tree = ast.parse(src_text)
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name == func_name:
            body = node.body
            if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant):
                body = body[1:]
            return ast.dump(ast.Module(body=body, type_ignores=[]))
    return None


def verify_scoring_function(func_name, this_module_globals):
    script21_text = SCRIPT21_PATH.read_text(encoding="utf-8")
    this_file_text = SCRIPT_PATH.read_text(encoding="utf-8")
    ref = _normalize_func_src(func_name, script21_text)
    mine = _normalize_func_src(func_name, this_file_text)
    return ref is not None and mine is not None and ref == mine


