def fusion_fwd(model, batch):
    xb, sb, yb = batch
    return model(xb, sb), yb


def train_one_seed(seed, pf, pos_weight):
    pf23 = pf["pf23"]
    train_df, val_df = pf23["train_df"], pf23["val_df"]
    sym_train_df, sym_val_df = pf23["sym_train_df"], pf23["sym_val_df"]
    top25 = pf23["top25_features"]

    y_train_full = train_df["Label"].to_numpy(dtype=np.float32)
    y_val_full = val_df["Label"].to_numpy(dtype=np.float32)

    me.set_seed(seed)

    raw_train_arr = train_df[top25].to_numpy(dtype=np.float32)
    raw_val_arr = val_df[top25].to_numpy(dtype=np.float32)
    sym_train_arr = sym_train_df[STAT_TOP6].to_numpy(dtype=np.float32)
    sym_val_arr = sym_val_df[STAT_TOP6].to_numpy(dtype=np.float32)

    train_ds = me.MainExperimentDataset("fusion", me.WINDOW, y_train_full, raw_train_arr, sym_train_arr)
    val_ds = me.MainExperimentDataset("fusion", me.WINDOW, y_val_full, raw_val_arr, sym_val_arr)
    train_loader = DataLoader(train_ds, batch_size=me.BATCH_SIZE, shuffle=True, num_workers=0)
    val_loader = DataLoader(val_ds, batch_size=me.BATCH_SIZE, shuffle=False, num_workers=0)

    model = me.FusionModel(raw_input_size=len(top25), symbolic_input_size=len(STAT_TOP6),
                            hidden_size=me.HIDDEN_SIZE, num_layers=me.NUM_LAYERS, dropout=me.DROPOUT)

    t0 = time.time()
    model, best_epoch, best_val_loss, loss_history_df = me.train_model(
        model, train_loader, val_loader, pos_weight, fusion_fwd, f"stat_top6_seed{seed}")
    train_elapsed = time.time() - t0

    model.eval()
    all_probs, all_labels = [], []
    with torch.no_grad():
        for batch in val_loader:
            logits, yb = fusion_fwd(model, batch)
            all_probs.append(torch.sigmoid(logits).numpy())
            all_labels.append(yb.numpy())
    y_prob = np.concatenate(all_probs)
    y_true = np.concatenate(all_labels)

    threshold, sweep_df, _ = me.select_threshold(y_true, y_prob)
    y_pred = (y_prob >= threshold).astype(int)
    metrics = me.compute_metrics(y_true, y_pred, y_prob)
    latency = me.measure_latency_ms_per_sequence(model, val_loader, fusion_fwd)

    config = {"hidden_size": me.HIDDEN_SIZE, "num_layers": me.NUM_LAYERS, "dropout": me.DROPOUT,
              "lr": me.LR, "batch_size": me.BATCH_SIZE, "max_epochs": me.MAX_EPOCHS,
              "patience": me.PATIENCE, "seed": seed, "window": me.WINDOW, "stride": me.STRIDE,
              "raw_cols": top25, "sym_cols": STAT_TOP6}

    prefix = RESULTS_DIR / f"stat_top6_seed{seed}"
    torch.save(model.state_dict(), f"{prefix}_checkpoint.pt")
    loss_history_df.to_csv(f"{prefix}_loss_history.csv", index=False)
    pd.DataFrame({"y_true": y_true, "y_prob": y_prob}).to_csv(f"{prefix}_validation_predictions.csv", index=False)
    meta = {"model_name": "stat_top6", "seed": seed, "best_epoch": best_epoch,
            "best_validation_bce_loss": best_val_loss, "selected_threshold": float(threshold),
            "latency_ms_per_sequence": latency, "metrics": metrics, "config": config,
            "train_elapsed_seconds": train_elapsed}
    with open(f"{prefix}_metadata.json", "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2, default=str)
    log(f"  seed {seed}: best_epoch={best_epoch}, threshold={threshold:.6f}, "
        f"VAL MCC={metrics['MCC']:.4f} F1={metrics['F1']:.4f} AUC={metrics['ROC_AUC']:.4f}")
    return meta


def evaluate_test_one_seed(seed, pf, val_meta):
    """TEST paths defined only here, only after this seed's training + VALIDATION
    threshold selection is complete."""
    TEST_UNSCALED_PATH = PROCESSED_DIR / "test_unscaled.csv"
    TEST_SCALED_PATH = PROCESSED_DIR / "test_scaled.csv"

    pf23 = pf["pf23"]
    top25 = pf23["top25_features"]
    threshold = val_meta["selected_threshold"]

    raw_needed = sorted({t for spec in STAT_TOP6_SPECS.values() for t in spec[1:]})
    test_raw = pd.read_csv(TEST_UNSCALED_PATH, usecols=["Label"] + raw_needed)
    test_scaled = pd.read_csv(TEST_SCALED_PATH)

    sym_test = {}
    for fname, (kind, a, b, ref) in pf["refs"].items():
        if kind == "state2":
            sym_test[fname] = score_state_2way(test_raw, a, b, ref)
        elif kind == "valve3":
            sym_test[fname] = score_valve_state_3way(test_raw, a, b, ref)
        else:
            sym_test[fname] = score_sensor_residual(test_raw, a, b, kind, ref)
    sym_test_df = pd.DataFrame(sym_test)
    # zero-fill undefined scores (transitional valve states etc.), identical
    # policy to script 21/26 (Decision 1 of the frozen experiment protocol)
    sym_test_df = sym_test_df.fillna(0.0)

    y_test_full = test_scaled["Label"].to_numpy(dtype=np.float32)
    raw_test_arr = test_scaled[top25].to_numpy(dtype=np.float32)
    sym_test_arr = sym_test_df[STAT_TOP6].to_numpy(dtype=np.float32)

    test_ds = me.MainExperimentDataset("fusion", me.WINDOW, y_test_full, raw_test_arr, sym_test_arr)
    test_loader = DataLoader(test_ds, batch_size=me.BATCH_SIZE, shuffle=False, num_workers=0)

    model = me.FusionModel(raw_input_size=len(top25), symbolic_input_size=len(STAT_TOP6),
                            hidden_size=me.HIDDEN_SIZE, num_layers=me.NUM_LAYERS, dropout=me.DROPOUT)
    ckpt_path = RESULTS_DIR / f"stat_top6_seed{seed}_checkpoint.pt"
    model.load_state_dict(torch.load(ckpt_path, map_location="cpu"))
    model.eval()

    all_probs, all_labels = [], []
    with torch.no_grad():
        for batch in test_loader:
            logits, yb = fusion_fwd(model, batch)
            all_probs.append(torch.sigmoid(logits).numpy())
            all_labels.append(yb.numpy())
    y_prob = np.concatenate(all_probs)
    y_true = np.concatenate(all_labels)
    y_pred = (y_prob >= threshold).astype(int)
    metrics = me.compute_metrics(y_true, y_pred, y_prob)
    latency = me.measure_latency_ms_per_sequence(model, test_loader, fusion_fwd)

    prefix = RESULTS_DIR / f"stat_top6_seed{seed}_test"
    pd.DataFrame({"y_true": y_true, "y_prob": y_prob}).to_csv(f"{prefix}_predictions.csv", index=False)
    test_meta = {"model_name": "stat_top6", "seed": seed, "threshold_source": str(RESULTS_DIR / f"stat_top6_seed{seed}_metadata.json"),
                 "selected_threshold": float(threshold), "latency_ms_per_sequence": latency,
                 "n_test_sequences": len(y_true), "metrics": metrics}
    with open(f"{prefix}_metadata.json", "w", encoding="utf-8") as f:
        json.dump(test_meta, f, indent=2, default=str)
    log(f"  seed {seed}: TEST MCC={metrics['MCC']:.4f} F1={metrics['F1']:.4f} AUC={metrics['ROC_AUC']:.4f}")
    return test_meta


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", action="store_true",
                         help="Run the full protocol: train 5 seeds, select VALIDATION thresholds, "
                              "then evaluate TEST for all 5 seeds, then aggregate.")
    args = parser.parse_args()

    section("MATCHED CONTROL EXPERIMENT — STATISTICAL-TOP-6")
    log(f"Run start: {RUN_START.isoformat()}")
    log(f"Mode: {'FULL RUN' if args.run else 'PREFLIGHT + VERIFICATION ONLY'}")

    pf = run_preflight()
    if not pf["all_passed"]:
        section("PREFLIGHT/VERIFICATION FAILED — ABORTING BEFORE ANY TRAINING")
        sys.exit(1)

    if not args.run:
        section("PREFLIGHT + VERIFICATION PASSED — STOPPING HERE (pass --run for the full protocol)")
        return

    section("PHASE 1 — TRAINING 5 SEEDS + VALIDATION THRESHOLD SELECTION")
    pf23 = pf["pf23"]
    train_df = pf23["train_df"]
    y_train_full = train_df["Label"].to_numpy(dtype=np.float32)
    train_seq_labels = y_train_full[me.WINDOW - 1:]
    n_pos, n_neg = float((train_seq_labels == 1).sum()), float((train_seq_labels == 0).sum())
    pos_weight = torch.tensor(n_neg / n_pos, dtype=torch.float32)
    log(f"pos_weight (TRAIN sequence labels only) = {pos_weight.item():.6f} (identical for every seed/model)")

    val_metas = {}
    for seed in SEEDS:
        meta_path = RESULTS_DIR / f"stat_top6_seed{seed}_metadata.json"
        if meta_path.exists():
            with open(meta_path, encoding="utf-8") as f:
                val_metas[seed] = json.load(f)
            log(f"  seed {seed}: already trained, resuming from {meta_path.name}")
            continue
        log(f"\n--- Training seed {seed} ---")
        val_metas[seed] = train_one_seed(seed, pf, pos_weight)

    section("PHASE 2 — TEST EVALUATION (one-shot per seed, after VALIDATION threshold is frozen)")
    test_metas = {}
    for seed in SEEDS:
        tmeta_path = RESULTS_DIR / f"stat_top6_seed{seed}_test_metadata.json"
        if tmeta_path.exists():
            with open(tmeta_path, encoding="utf-8") as f:
                test_metas[seed] = json.load(f)
            log(f"  seed {seed}: TEST already evaluated, resuming from {tmeta_path.name}")
            continue
        log(f"\n--- Evaluating TEST, seed {seed} ---")
        test_metas[seed] = evaluate_test_one_seed(seed, pf, val_metas[seed])

    section("PHASE 3 — AGGREGATION")
    rows = []
    for seed in SEEDS:
        vm, tm = val_metas[seed]["metrics"], test_metas[seed]["metrics"]
        rows.append({
            "Model": "stat_top6", "Seed": seed,
            "VAL_MCC": vm["MCC"], "VAL_F1": vm["F1"], "VAL_ROC_AUC": vm["ROC_AUC"],
            "TEST_MCC": tm["MCC"], "TEST_F1": tm["F1"], "TEST_ROC_AUC": tm["ROC_AUC"],
            "Selected_Threshold": val_metas[seed]["selected_threshold"],
        })
    out_df = pd.DataFrame(rows)
    out_path = TABLES_OUT_DIR / "stat_top6_results_long.csv"
    out_df.to_csv(out_path, index=False)
    log(f"Wrote {out_path}")
    log(out_df.to_string(index=False))

    log("\nRUN COMPLETE.")


if __name__ == "__main__":
    main()
